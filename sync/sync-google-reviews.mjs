// Pulls live Google reviews into data/reviews.js.
// Usage: GOOGLE_PLACES_KEY=... GOOGLE_PLACE_ID=... node sync/sync-google-reviews.mjs
// Run nightly from .github/workflows/sync-reviews.yml (Node 18+, no dependencies).
import { writeFile } from 'node:fs/promises';

const key = process.env.GOOGLE_PLACES_KEY;
const placeId = process.env.GOOGLE_PLACE_ID;
if (!key || !placeId) {
  console.error('Set GOOGLE_PLACES_KEY and GOOGLE_PLACE_ID');
  process.exit(1);
}

const res = await fetch(`https://places.googleapis.com/v1/places/${placeId}`, {
  headers: {
    'X-Goog-Api-Key': key,
    'X-Goog-FieldMask': 'displayName,rating,userRatingCount,reviews,googleMapsUri',
  },
});
if (!res.ok) {
  console.error(`Places API ${res.status}: ${await res.text()}`);
  process.exit(1);
}
const place = await res.json();

const feed = {
  syncedAt: new Date().toISOString(),
  source: 'Google Business Profile',
  displayName: place.displayName?.text ?? 'Berkshire Custom Cleaning',
  rating: place.rating,
  userRatingCount: place.userRatingCount,
  googleMapsUri: place.googleMapsUri,
  writeReviewUri: `https://search.google.com/local/writereview?placeid=${placeId}`,
  reviews: (place.reviews ?? []).map(r => ({
    rating: r.rating,
    relativePublishTimeDescription: r.relativePublishTimeDescription,
    text: r.text?.text ?? r.originalText?.text ?? '',
    authorAttribution: {
      displayName: r.authorAttribution?.displayName ?? 'Google user',
      photoUri: r.authorAttribution?.photoUri ?? '',
    },
  })),
};

await writeFile(
  new URL('../data/reviews.js', import.meta.url),
  `/* Auto-generated by sync/sync-google-reviews.mjs — do not edit. */\nwindow.BCC_REVIEWS = ${JSON.stringify(feed, null, 2)};\n`
);
console.log(`Synced ${feed.reviews.length} reviews, ${feed.rating}★ from ${feed.userRatingCount} ratings`);
